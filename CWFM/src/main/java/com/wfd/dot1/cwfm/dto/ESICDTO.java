package com.wfd.dot1.cwfm.dto;

public class ESICDTO {

	private int totalEsic;
    private int activeEsic;
    private int esicPercentage;
	public int getTotalEsic() {
		return totalEsic;
	}
	public void setTotalEsic(int totalEsic) {
		this.totalEsic = totalEsic;
	}
	public int getActiveEsic() {
		return activeEsic;
	}
	public void setActiveEsic(int activeEsic) {
		this.activeEsic = activeEsic;
	}
	public int getEsicPercentage() {
		return esicPercentage;
	}
	public void setEsicPercentage(int esicPercentage) {
		this.esicPercentage = esicPercentage;
	}
    
}
