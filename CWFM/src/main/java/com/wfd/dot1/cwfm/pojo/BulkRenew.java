package com.wfd.dot1.cwfm.pojo;

public class BulkRenew {

	private String gatepassNumber;
	private String workOrder;
	private String wcNumber;
	private String llNumber;
	
	public String getGatepassNumber() {
		return gatepassNumber;
	}
	public void setGatepassNumber(String gatepassNumber) {
		this.gatepassNumber = gatepassNumber;
	}
	public String getWorkOrder() {
		return workOrder;
	}
	public void setWorkOrder(String workOrder) {
		this.workOrder = workOrder;
	}
	public String getWcNumber() {
		return wcNumber;
	}
	public void setWcNumber(String wcNumber) {
		this.wcNumber = wcNumber;
	}
	public String getLlNumber() {
		return llNumber;
	}
	public void setLlNumber(String llNumber) {
		this.llNumber = llNumber;
	}
	
}
